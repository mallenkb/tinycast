#!/usr/bin/env python3
"""Generate the dictation currency registry from a pinned Unicode CLDR snapshot."""
import hashlib
import json
from pathlib import Path
import re
import urllib.request
import xml.etree.ElementTree as ET


REVISION = "96e54b273d2da4ec6fbad350ba19ff23fa24a588"
BASE = f"https://raw.githubusercontent.com/unicode-org/cldr/{REVISION}/common"
DIGESTS = {
    "validity/currency.xml": "b046c1fa146666f2176275f28202196136267d50ee8d595f396655b0a8887ec7",
    "supplemental/supplementalData.xml": "745150ec1408d50e1a272b65654a5dd645f3e60f5cc2898b576f725b28538d1a",
    "main/en.xml": "f8cbf26964d0e349fc96d9e5a56292edcbaab25c8e64177ca4f111773dfb79cf",
}
OUTPUT = Path(__file__).resolve().parents[1] / (
    "Tinycast/Features/Dictation/Model/DictationCurrencyData.generated.swift"
)


def source(path):
    with urllib.request.urlopen(f"{BASE}/{path}", timeout=30) as response:
        contents = response.read()
    if hashlib.sha256(contents).hexdigest() != DIGESTS[path]:
        raise ValueError(f"CLDR digest mismatch for {path}")
    return ET.fromstring(contents)


def main():
    validity = source("validity/currency.xml")
    regular = validity.find("./idValidity/id[@type='currency'][@idStatus='regular']")
    codes = sorted(regular.text.split())
    if len(codes) != len(set(codes)) or not all(re.fullmatch("[A-Z]{3}", code) for code in codes):
        raise ValueError("Unexpected CLDR currency validity data")

    supplemental = source("supplemental/supplementalData.xml")
    digits = {
        item.get("iso4217"): int(item.get("digits"))
        for item in supplemental.findall("./currencyData/fractions/info")
    }
    english = source("main/en.xml")
    claims = {}
    for currency in english.findall("./numbers/currencies/currency"):
        code = currency.get("type")
        for display in currency.findall("./displayName[@count]"):
            name = display.text.lower()
            if " " in name and not any(mark in name for mark in "()"):
                claims.setdefault(name, set()).add(code)

    output = [
        "// Generated by Scripts/gen-dictation-currencies.py from Unicode CLDR 49.",
        "// Unicode CLDR data is distributed under https://www.unicode.org/license.txt.",
        "enum DictationCurrencyData {",
        "    static let digits: [String: Int] = [",
    ]
    output.extend(f'        "{code}": {digits.get(code, digits["DEFAULT"])},' for code in codes)
    output += ["    ]", "", "    static let englishNames: [String: String] = ["]
    output.extend(
        f"        {json.dumps(name, ensure_ascii=False)}: \"{next(iter(owners))}\","
        for name, owners in sorted(claims.items())
        if len(owners) == 1 and next(iter(owners)) in codes
    )
    output += ["    ]", "}", ""]
    OUTPUT.write_text("\n".join(output), encoding="utf-8")


if __name__ == "__main__":
    main()
